"""
Run the seven documented detection scenarios (A–G) through the real engine
and write the ACTUAL results to reports/scenario_results.md.

    python scripts/run_scenarios.py

No backend needed. Uses the trained baseline + ML model if present.
"""

import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from ids.engine import HybridIDSEngine  # noqa: E402
from ids.validation import format_timestamp  # noqa: E402

T0 = datetime(2026, 9, 28, 12, 0, tzinfo=timezone.utc)


def flow(offset=0, **kw):
    base = {"timestamp": format_timestamp(T0 + timedelta(seconds=offset)),
            "source_ip": "192.0.2.15", "destination_ip": "198.51.100.20", "source_port": 49152,
            "destination_port": 443, "protocol": "TCP", "packet_count": 18, "byte_count": 12400,
            "duration_seconds": 2.8, "connection_count": 3, "failed_connection_count": 0,
            "syn_count": 2, "rst_count": 0}
    base.update(kw)
    return base


SCENARIOS = [
    ("A", "Normal HTTPS browsing", "TCP/443, 18 pkts, 12.4 KB, 2.8 s, 3 conns, 0 failed", [flow()]),
    ("B", "Normal DNS query pattern", "UDP/53, 2 pkts, 150 B, 0.02 s", [flow(
        10, source_ip="192.0.2.30", destination_ip="198.51.100.53", destination_port=53,
        protocol="UDP", packet_count=2, byte_count=150, duration_seconds=0.02, connection_count=1,
        syn_count=0)]),
    ("C", "Repeated failed connection pattern", "TCP/22, 70 conns, 60 failed, 60 s", [flow(
        20, source_ip="203.0.113.160", destination_ip="198.51.100.22", destination_port=22,
        packet_count=300, byte_count=24000, duration_seconds=60, connection_count=70,
        failed_connection_count=60, syn_count=70, rst_count=60)]),
    ("D", "High connection rate", "TCP/443, 500 conns in 10 s", [flow(
        30, source_ip="203.0.113.170", packet_count=2500, byte_count=200000, duration_seconds=10,
        connection_count=500, failed_connection_count=40, syn_count=500, rst_count=40)]),
    ("E", "Multi-port probing-like pattern", "one source -> 20 ports in 20 s (1 pkt each)", [flow(
        40 + k, source_ip="203.0.113.180", destination_ip="198.51.100.41", source_port=40000 + k,
        destination_port=p, packet_count=1, byte_count=60, duration_seconds=0.01,
        connection_count=1, failed_connection_count=1, syn_count=1, rst_count=1)
        for k, p in enumerate([21, 22, 23, 25, 53, 80, 110, 135, 139, 143, 443, 445, 993,
                               1433, 3306, 3389, 5432, 5900, 8080, 8443])]),
    ("F", "SYN-heavy statistical pattern", "2000 pkts, 1800 SYN, 1200 conns (1100 failed), 10 s", [flow(
        80, source_ip="203.0.113.190", packet_count=2000, syn_count=1800, byte_count=120000,
        duration_seconds=10, connection_count=1200, failed_connection_count=1100, rst_count=50)]),
    ("G", "Abnormally high traffic volume", "2 GB outbound in 300 s to external host", [flow(
        90, source_ip="192.0.2.60", destination_ip="203.0.113.210", byte_count=2_000_000_000,
        packet_count=1_430_000, duration_seconds=300, connection_count=1, syn_count=1)]),
]


def main():
    engine = HybridIDSEngine.from_project_files()
    lines = [
        "# Scenario Results (actual engine output)",
        "",
        f"_Generated by `python scripts/run_scenarios.py` — ML {'enabled' if engine.ml_enabled else 'disabled'}._",
        "",
        "| # | Scenario | Input | Key features | Rules triggered | Sig / Anom / ML | Risk | Classification | Alert |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for code, name, desc, flows in SCENARIOS:
        results = [engine.analyze(f) for f in flows]
        r = results[-1]
        f = r["features"]
        feats = (f"conn_rate={f['connection_rate']:.1f}/s, fail_ratio={f['failure_ratio']:.2f}, "
                 f"syn_ratio={f['syn_ratio']:.2f}, uniq_ports={f['unique_destination_ports']:.0f}, "
                 f"B/s={f['bytes_per_second']:,.0f}")
        rules = ", ".join(f"{m['rule_id']} {m['name']}" for m in r["rule_matches"]) or "none"
        ml = "—" if r["ml_probability"] is None else f"{r['ml_probability'] * 100:.0f}"
        alert = (f"{r['alert']['severity']} — {r['alert']['alert_type']}" if r["alert"] else "none")
        if len(results) > 1:
            first = next((i for i, x in enumerate(results) if any(
                m["rule_id"] == "IDS-003" for m in x["rule_matches"])), None)
            alerted = sum(1 for x in results if x["alert"])
            alert += (f" (IDS-003 first fired on record {first + 1}/{len(results)}; "
                      f"{alerted}/{len(results)} records alerted)")
        lines.append(f"| {code} | {name} | {desc} | {feats} | {rules} | {r['signature_score']:.0f} / "
                     f"{r['anomaly']['score']:.0f} / {ml} | {r['risk_score']} ({r['risk_band']}) | "
                     f"{r['classification']} | {alert} |")
        print(f"Scenario {code}: {name:<36} risk={r['risk_score']:<5} {r['classification']:<20} {rules}")
    out = PROJECT_ROOT / "reports" / "scenario_results.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n[+] Written to {out}")


if __name__ == "__main__":
    main()
