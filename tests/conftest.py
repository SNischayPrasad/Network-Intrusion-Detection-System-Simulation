# --------------------------------------------------------------------------
# Test-report generation
# --------------------------------------------------------------------------
_RESULTS = []


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    rep.tc_doc = (item.function.__doc__ or "").strip()


def pytest_runtest_logreport(report):
    if report.when == "call" or (report.when == "setup" and report.outcome != "passed"):
        actual = dict(report.user_properties).get("actual", "")
        if report.failed:
            actual = (actual + " | " if actual else "") + \
                str(report.longrepr).strip().splitlines()[-1][:160]
        _RESULTS.append((getattr(report, "tc_doc", ""), report.nodeid, report.outcome, actual))


def pytest_sessionfinish(session, exitstatus):
    if not _RESULTS:
        return
    rows = []
    for doc, nodeid, outcome, actual in _RESULTS:
        parts = [p.strip() for p in doc.split("|")] if doc.startswith("TC-") else []
        tc, scen, inp, exp = (parts + ["", "", "", ""])[:4] if parts else ("—", nodeid, "", "")
        rows.append((tc, scen, inp, exp.replace("Expected:", "").strip(), actual,
                     "PASS" if outcome == "passed" else outcome.upper()))
    rows.sort(key=lambda r: (r[0] == "—", r[0]))
    passed = sum(r[5] == "PASS" for r in rows)
    lines = [
        "# Automated Test Results",
        "",
        f"_Generated by pytest on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}_ — "
        f"**{passed}/{len(rows)} passed**",
        "",
        "| Test ID | Scenario | Input | Expected Result | Actual Result | Pass/Fail |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append("| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |")
    out = PROJECT_ROOT / "reports" / "test_results.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
