"""
Shared pytest fixtures + an automatic test-report generator.

Every test's docstring follows the format
    "TC-XX | Scenario | Input | Expected"
and tests call `record_property("actual", "...")` with what they observed.
At the end of the run reports/test_results.md is written with
Test ID / Scenario / Input / Expected / Actual / Pass-Fail for every test.
"""

